def persona_identity_block(persona: Persona) -> str:
    """Return the unified persona identity block for system prompts.

    平台对话助手（``chat._system_prompt``）与对局陪玩 Agent
    （``dialogue_engine._system_prompt``）共用此出口，保证用户在 profile
    选一次人设后，两层身份连贯——同一个内核、同一份说话习惯约束。
    """
    return f"你是 Gavis 的{persona.display_name}。{persona.character}\n说话习惯：{persona.style_guide}"


def _assert_coverage() -> None:
    """校验每个 Persona 覆盖全部场景（导入期自检，防御性约束）."""
    for persona in PERSONAS.values():
        missing = [scenario for scenario in SCENARIOS if scenario not in persona.fallback_lines]
        if missing:
            raise ValueError(f"Persona {persona.key!r} 缺少兜底场景: {missing}")


